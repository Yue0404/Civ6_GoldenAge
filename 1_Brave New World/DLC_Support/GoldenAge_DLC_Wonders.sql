WHERE ModifierId = 'APADANA_AWARD_TWO_INFLUENCE_TOKEN_MODIFIER' AND Name = 'Amount' AND EXISTS (SELECT * FROM Buildings WHERE BuildingType='BUILDING_APADANA');

