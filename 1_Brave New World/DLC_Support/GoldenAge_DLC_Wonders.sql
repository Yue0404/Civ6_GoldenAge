UPDATE Modifiers SET ModifierType = "MODIFIER_PLAYER_CITIES_ATTACH_MODIFIER", SubjectRequirementSetId = NULL
WHERE ModifierId = 'APADANA_AWARD_TWO_INFLUENCE_TOKEN' AND EXISTS (SELECT * FROM Buildings WHERE BuildingType='BUILDING_APADANA');

